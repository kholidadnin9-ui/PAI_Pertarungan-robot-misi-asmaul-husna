// Processes AI-generated source images into compact base64 TS modules (src/assets/*.ts)
// and detects each robot's gun-muzzle + body-hit points (fractions of the image box).
const sharp = require('sharp');
const fs = require('fs');
const path = require('path');

const names = ['pink', 'orange', 'green', 'blue', 'red'];
const OUT = 'src/assets';
fs.mkdirSync(OUT, { recursive: true });

async function cutout(name) {
  const input = path.join('public/raw', `robot-${name}.png`);
  const { data, info } = await sharp(input).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  const isBg = (i) => {
    const r = data[i], g = data[i + 1], b = data[i + 2];
    const mn = Math.min(r, g, b), mx = Math.max(r, g, b);
    return mn > 205 && mx - mn < 45;
  };
  const visited = new Uint8Array(w * h);
  const stack = [];
  for (let x = 0; x < w; x++) stack.push(x, 0, x, h - 1);
  for (let y = 0; y < h; y++) stack.push(0, y, w - 1, y);
  while (stack.length) {
    const y = stack.pop(); const x = stack.pop();
    if (x < 0 || y < 0 || x >= w || y >= h) continue;
    const p = y * w + x;
    if (visited[p]) continue;
    visited[p] = 1;
    if (!isBg(p * 4)) continue;
    data[p * 4 + 3] = 0;
    stack.push(x + 1, y, x - 1, y, x, y + 1, x, y - 1);
  }
  const removed = (x, y) => x >= 0 && y >= 0 && x < w && y < h && data[(y * w + x) * 4 + 3] === 0;
  const alpha = new Uint8Array(w * h);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const p = y * w + x;
    if (data[p * 4 + 3] === 0) continue;
    if (removed(x + 1, y) || removed(x - 1, y) || removed(x, y + 1) || removed(x, y - 1)) {
      const mn = Math.min(data[p * 4], data[p * 4 + 1], data[p * 4 + 2]);
      const whiteness = Math.max(0, Math.min(1, (mn - 140) / 100));
      alpha[p] = Math.round(255 * (1 - whiteness * 0.85));
    } else alpha[p] = 255;
  }
  for (let p = 0; p < w * h; p++) if (data[p * 4 + 3] !== 0) data[p * 4 + 3] = alpha[p];

  const png = await sharp(data, { raw: { width: w, height: h, channels: 4 } }).png().toBuffer();
  const finalBuf = await sharp(png).trim({ threshold: 10 }).resize({ height: 520, fit: 'inside' }).png().toBuffer();
  const fin = await sharp(finalBuf).raw().toBuffer({ resolveWithObject: true });
  const meta = analyze(fin.data, fin.info.width, fin.info.height);

  const webp = await sharp(finalBuf).webp({ quality: 86, alphaQuality: 90, effort: 6 }).toBuffer();
  fs.writeFileSync(path.join(OUT, `robot-${name}.ts`), `// auto-generated by scripts/process-assets.cjs\nconst src = 'data:image/webp;base64,${webp.toString('base64')}';\nexport default src;\n`);
  return { name, w: fin.info.width, h: fin.info.height, kb: Math.round(webp.length / 1024), ...meta, finalBuf };
}

function analyze(d, w, h) {
  const A = (x, y) => d[(y * w + x) * 4 + 3];
  const y0 = Math.floor(h * 0.12), y1 = Math.floor(h * 0.85);
  let xmax = 0, yAtMax = 0;
  for (let y = y0; y < y1; y++) for (let x = w - 1; x > xmax; x--) if (A(x, y) > 128) { xmax = x; yAtMax = y; break; }
  // vertical extent of the barrel a few px inside the tip
  const cx = Math.max(0, xmax - 6);
  let top = yAtMax, bot = yAtMax;
  while (top > 0 && A(cx, top - 1) > 128) top--;
  while (bot < h - 1 && A(cx, bot + 1) > 128) bot++;
  const muzzle = { x: +(xmax / w).toFixed(3), y: +(((top + bot) / 2) / h).toFixed(3) };
  // torso centroid (exclude gun area on the right)
  let sx = 0, sy = 0, n = 0;
  for (let y = Math.floor(h * 0.22); y < Math.floor(h * 0.55); y++) for (let x = 0; x < Math.floor(w * 0.62); x++) if (A(x, y) > 200) { sx += x; sy += y; n++; }
  const hit = { x: +((sx / n) / w).toFixed(3), y: +((sy / n) / h).toFixed(3) };
  return { muzzle, hit, barrel: +(((bot - top) / h)).toFixed(3) };
}

(async () => {
  const results = [];
  for (const n of names) results.push(await cutout(n));
  // background
  const bg = await sharp('public/images/bg-city.jpg').resize({ width: 1440 }).webp({ quality: 70, effort: 6 }).toBuffer();
  fs.writeFileSync(path.join(OUT, 'bg.ts'), `// auto-generated by scripts/process-assets.cjs\nconst src = 'data:image/webp;base64,${bg.toString('base64')}';\nexport default src;\n`);
  console.log('bg', Math.round(bg.length / 1024) + 'KB');

  // debug sheet with markers
  const comps = []; let x = 10;
  for (const r of results) {
    const scaled = await sharp(r.finalBuf).resize({ height: 360 }).toBuffer();
    const m = await sharp(scaled).metadata();
    const mk = (cx, cy, color) => Buffer.from(`<svg width="${m.width}" height="360"><circle cx="${cx * m.width}" cy="${cy * 360}" r="9" fill="none" stroke="${color}" stroke-width="4"/><circle cx="${cx * m.width}" cy="${cy * 360}" r="2" fill="${color}"/></svg>`);
    const marked = await sharp(scaled).composite([{ input: mk(r.muzzle.x, r.muzzle.y, '#00ff00') }, { input: mk(r.hit.x, r.hit.y, '#ffff00') }]).png().toBuffer();
    comps.push({ input: marked, left: x, top: 10 });
    x += m.width + 10;
    delete r.finalBuf;
    console.log(JSON.stringify(r));
  }
  await sharp({ create: { width: x, height: 380, channels: 4, background: '#2a4f9a' } }).composite(comps).jpeg({ quality: 85 }).toFile('/tmp/markers.jpg');
})();
